"""Build reports/hw08/METRICS.md from reports/hw08/raw/ (no numbers typed by hand)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "reports" / "hw08" / "raw"
OUT = ROOT / "reports" / "hw08" / "METRICS.md"


def load(name: str) -> dict:
    path = RAW / name
    return json.loads(path.read_text()) if path.exists() else {}


def main() -> None:
    dup, death = load("failure_duplicate.json"), load("failure_consumer_death.json")
    poison, order, journey = load("failure_poison.json"), load("failure_ordering.json"), load("pipeline_journey.json")
    lines = ["# HW8 Metrics", "", "Generated by `scripts/build_hw8_metrics.py` from `reports/hw08/raw/`.", ""]

    lines += ["## Part 1 - Topics and message schemas", "",
              "| Topic | Partitions | Producer -> consumer |", "|---|---:|---|",
              "| `s0036_report_requests` | 1 | client / FastAPI -> report worker |",
              "| `s0036_report_responses` | 1 | report worker -> client / FastAPI |",
              "| `s0036_inbox` | 1 | send_question.py -> Planner |", "| `s0036_tasks` | 2 | Planner -> Writer |",
              "| `s0036_drafts` | 1 | Writer -> Reviewer |", "| `s0036_final` | 1 | Reviewer -> reader |",
              "| `s0036_dead_letter` | 1 | any agent -> operator |", "",
              "Request: `{\"correlation_id\", \"reply_to\": \"s0036_report_responses\", \"operation\": "
              "\"CREATE_REPORT\" | \"GET_REPORT\", \"data\": {...}}`.  ",
              "Success: `{\"correlation_id\", \"success\": true, \"report_id\", \"message\": \"Report created\"}` or "
              "`{\"correlation_id\", \"success\": true, \"report\": {...}}`.  ",
              "Error: `{\"correlation_id\", \"success\": false, \"error\": \"Report not found\" | \"Unknown operation\" "
              "| validation message}`.", ""]

    if journey:
        final = (journey.get("final") or {}).get("value", {})
        lines += ["## Part 2 - One message journey", "",
                  f"correlation_id `{journey['correlation_id']}` preserved inbox -> tasks -> drafts -> final; "
                  f"final status **{final.get('status')}**, review checks {final.get('review', {}).get('checks')}.", ""]

    def cell(text: str) -> str:
        return text.replace("|", "\\|")

    rows = []
    if dup:
        b, a = dup["before_fix"], dup["after_fix"]
        rows.append(("Duplicate delivery (same correlation_id replayed)",
                     f"{b['tasks_produced']} tasks, {b['final_messages']} final answers for one question",
                     f"{a['tasks_produced']} task, {a['final_messages']} final answer; replay logged "
                     f"'DUPLICATE skipped' ({a['duplicates_skipped']}x)"))
    if death:
        b, a = death["before_fix"], death["after_fix"]
        rows.append(("Consumer killed mid-work (SIGKILL during processing)",
                     f"offset committed on receipt ({b['committed_after_kill']} vs task offset {b['task_offset']}); "
                     f"after restart: redelivered={b['redelivered_after_restart']}, drafts={b['drafts_produced']} "
                     "(task lost)",
                     f"offset not committed ({a['committed_after_kill']} = task offset {a['task_offset']}); after "
                     f"restart: redelivered={a['redelivered_after_restart']}, drafts={a['drafts_produced']}, "
                     f"committed -> {a['committed_at_end']}"))
    if poison:
        b, a = poison["before_fix"], poison["after_fix"]
        rows.append(("Poison message (plan is not a list), good message behind it",
                     f"{b['attempts_on_bad_message']} attempts in 25 s, never dead-lettered; good message processed: "
                     f"{b['good_message_processed_within_25s']} (partition blocked)",
                     f"{a['attempts_on_bad_message']} attempts -> moved to s0036_dead_letter "
                     f"({a['moved_to_dead_letter']}); good message processed: "
                     f"{a['good_message_processed_within_25s']}"))
    if order:
        b, a = order["run1_no_key"], order["run2_key_entity"]
        rows.append(("Two partitions / two consumers (20 VERIFY_SEED messages)",
                     f"no key: {len(b['violations'])} of 4 entities out of order: "
                     + "; ".join(f"{v['entity']} {v['processed_seq_order']} on partitions {v['partitions']}"
                                 for v in b["violations"]),
                     f"key = entity: {len(a['violations'])} out of order; each entity on one partition "
                     + "; ".join(f"{e}->p{v['partitions'][0]}" for e, v in a["per_entity"].items())))
    lines += ["## Part 3 - Failure table", "", "| Failure scenario | Before fix | After fix |", "|---|---|---|"]
    lines += [f"| {cell(s)} | {cell(b)} | {cell(a)} |" for s, b, a in rows]
    lines += ["", "Raw evidence: `raw/failure_duplicate.json`, `raw/failure_consumer_death.json`, "
              "`raw/failure_poison.json`, `raw/failure_ordering.json`, `raw/ordering_run1_no_key.csv`, "
              "`raw/ordering_run2_key_entity.csv`, per-process logs in `raw/runs/`.", ""]

    if order:
        for label, title in (("run1_no_key", "Ordering run 1 - no key"), ("run2_key_entity", "Ordering run 2 - key = entity")):
            lines += [f"### {title}", "", "| Entity | Processing order of seq | Partitions | In order |",
                      "|---|---|---|---|"]
            for e, v in order[label]["per_entity"].items():
                seqs = v["processed_seq_order"]
                lines.append(f"| {e} | {seqs} | {v['partitions']} | {'yes' if seqs == sorted(seqs) else 'NO'} |")
            lines.append("")

    lines += ["## Comparison with the HW2 in-process graph", "",
              "**Benefits gained by moving to Kafka**", "",
              "1. Decoupled failure: when the Writer was killed, the Planner and Reviewer kept running and the task "
              "waited in `s0036_tasks` until the Writer restarted and finished it. In HW2 one exception in a node "
              "stopped the whole graph run.",
              "2. Independent scaling: a second Writer joined the same consumer group and Kafka split the two "
              "partitions of `s0036_tasks` between them, with no change to the Planner or Reviewer.", "",
              "**New responsibilities I now handle myself**", "",
              "1. Duplicate delivery: Kafka is at-least-once, so a replayed or redelivered message is processed again "
              "unless each agent is idempotent (persisted set of completed correlation_ids).",
              "2. Ordering and offsets: order holds only within one partition, so related messages need a key; and "
              "offsets must be committed only after the output is in Kafka, with bounded retries plus a dead-letter "
              "topic so one bad message cannot block a partition. In HW2 a function call simply returned in order, "
              "exactly once.", ""]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
