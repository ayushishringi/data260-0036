"""Build reports/hw10/METRICS.md from the HW10 raw files (no model calls).

Usage: make metrics-hw10
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src import tracing  # noqa: E402
from src.hw10_stats import coordination_text, eval_summary, trace_path  # noqa: E402

RAW = ROOT / "reports" / "hw10" / "raw"
OUT = ROOT / "reports" / "hw10" / "METRICS.md"


def load(name: str) -> dict | None:
    path = RAW / name
    return json.loads(path.read_text()) if path.exists() else None


def fmt(v: object, spec: str = "") -> str:
    return "-" if v is None else format(v, spec)


def main() -> None:
    lines = ["# HW10 metrics (s0036)", "", "Generated by `make metrics-hw10` from `reports/hw10/raw/` and "
             "`reports/hw10/traces/spans.jsonl`. Judge: DeepEval GEval on Ollama qwen3:4b (temperature 0, seed 36, "
             "num_ctx 16384, thinking on), 1-5 rubric.", ""]
    spans = tracing.load_spans()

    e2e = load("e2e_run.json")
    if e2e:
        lines += ["## Part 2: end-to-end evaluation", "", f"Run {e2e['ran_at']}.", "",
                  "| trace_id | question | Plan | Writer | Final | Draft (final criterion) | Final - draft |",
                  "|---|---|---|---|---|---|---|"]
        evals = [e for e in e2e["evaluations"] if e["outcome"] == "evaluated"]
        for e in evals:
            fv = e["final_vs_draft"]
            lines.append(f"| `{e['trace_id']}` | {e['question']} | {e['plan_quality']['score']} | "
                         f"{e['writer_helpfulness']['score']} | {e['final_helpfulness']['score']} | "
                         f"{fv['draft_score']} | {fv['difference']} |")
        lines.append("")
        for e in evals:
            lines.append(f"- `{e['trace_id'][:8]}`: {e['final_vs_draft']['interpretation']}")
        lines += ["", "**Coordination (Part 2 traces):**", ""]
        lines += [f"- {t}" for t in coordination_text(eval_summary(evals))]
        lines.append("")

    ex = load("trace_examples.json")
    if ex:
        lines += ["## Part 4.2: trace examples", "", "| kind | trace_id | path | stages | status / error |",
                  "|---|---|---|---|---|"]
        for kind, item in ex.items():
            t = tracing.trace(spans, item["trace_id"])
            errs = [s for s in t if s["status"] != "ok"]
            status = f"error at {errs[0]['stage']}: {errs[0]['error']}" if errs else "ok"
            lines.append(f"| {kind} | `{item['trace_id']}` | {trace_path(t)} | "
                         f"{' → '.join(dict.fromkeys(s['stage'] for s in t))} | {status} |")
        lines.append("")

    lat = load("latency_run.json")
    if lat:
        st, v, h = lat["stage_latency"], lat["verification"], lat["cache_hit_latency"]
        lines += ["## Part 4.3: stage latency (50 cache misses)", "",
                  f"Run {lat['ran_at']} ({lat['duration_s'] / 60:.0f} min). Verification: {v['requests']} requests, "
                  f"{v['cache_lookup_miss']} cache_lookup=miss, {v['served_from_cache']} served from cache, "
                  f"{v['failed']} failed; {st['traces']} complete traces used.", "",
                  "| Stage | p50 (ms) | p95 (ms) | % of cache-miss end-to-end |", "|---|---|---|---|"]
        for t in st["table"]:
            lines.append(f"| {t['stage']} | {fmt(t['p50_ms'], ',.1f')} | {fmt(t['p95_ms'], ',.1f')} | "
                         f"{(t['share_of_e2e'] or 0):.1%} |")
        lines += ["", f"End-to-end (cache lookup start → evaluation end): p50 {st['end_to_end']['p50_ms']:,.0f} ms, "
                  f"p95 {st['end_to_end']['p95_ms']:,.0f} ms. User-facing (request span, answer returned): "
                  f"p50 {st['user_facing']['p50_ms']:,.0f} ms, p95 {st['user_facing']['p95_ms']:,.0f} ms.", "",
                  "Queue waits: " + ", ".join(f"{q['stage']} p50 {q['p50_ms']} / p95 {q['p95_ms']} ms"
                                              for q in st["queues"]) + ".", "",
                  f"Dominant contributor: **{st['dominant']}**.", "",
                  f"Cache-hit latency (separate metric, {h['n']} hits): p50 {h['p50_ms']} ms, p95 {h['p95_ms']} ms.", ""]

    val = load("judge_validation.json")
    lines += ["## Part 3: judge validation", ""]
    if not val:
        lines += ["Not run yet: label the drafts (`make label-hw10`), commit `eval_cases.json` and "
                  "`human_labels.csv`, then `make judge-hw10`.", ""]
    else:
        rep = val["repeatability"]
        lines += [f"Cases and labels frozen in commit `{val['frozen']['commit'][:7]}` ({val['frozen']['committed_at']}); "
                  f"judge run {val['ran_at']}.", "",
                  "| run | Spearman rho | p | mean abs diff | exact | within 1 | judge mean | human mean |",
                  "|---|---|---|---|---|---|---|---|"]
        for r in val["per_run"]:
            lines.append(f"| {r['run']} | {r['spearman_rho']} | {r['spearman_p']} | {r['mean_abs_diff']} | "
                         f"{r['exact_agreement']} | {r['within_1']} | {r['judge_mean']} | {r['human_mean']} |")
        m = val["mean_of_runs"]
        lines += [f"| mean of 3 | {m['spearman_rho']} | {m['spearman_p']} | {m['mean_abs_diff']} | - | - | "
                  f"{m['judge_mean']} | {m['human_mean']} |", "",
                  f"Repeatability: {rep['cases_changed']}/{rep['cases_scored_every_run']} cases changed score "
                  f"across 3 runs ({rep['change_rate']}); {rep['pairwise_changes']}/{rep['pairwise_comparisons']} "
                  f"run pairs differ; mean |change| {rep['mean_abs_change']}, max {rep['max_abs_change']}.", ""]
        with (RAW / "judge_vs_human.csv").open() as stream:
            rows = list(csv.DictReader(stream))
        lines += ["| case | category | human | run 1 | run 2 | run 3 |", "|---|---|---|---|---|---|"]
        lines += [f"| {r['case_id']} | {r['category']} | {r['human_label']} | {r['judge_run1']} | {r['judge_run2']} | "
                  f"{r['judge_run3']} |" for r in rows]
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
